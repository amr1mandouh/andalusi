export function getIdiomsForWord(wordId: string): Idiom[] {
  return idioms.filter((idiom) => idiom.relatedWordIds.includes(wordId));
}

export function getIdiomsForCategory(categoryId: string): Idiom[] {
  return idioms.filter((idiom) => idiom.categoryId === categoryId);
}

export function getIdiomCategoryIds(): string[] {
  const allCategoryIds = getAllLessons().map((lesson) => lesson.categoryId);
  return Array.from(new Set(idioms.map((idiom) => idiom.categoryId))).filter(
    (id) => allCategoryIds.includes(id),
  );
}

