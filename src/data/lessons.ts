import { numberToWords, NUMBER_MILESTONES } from './numbersLogic';

export interface Word {
  id: string;
  en: string;
  es: string;
  ar: string;
  emoji: string;
  pronunciation?: string;
  /** A short example sentence showing the word used in context, with translations. */
  context?: { es: string; en: string; ar: string };
}

export type Level = 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2';

export const LEVELS: Level[] = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

export const levelLabels: Record<Level, string> = {
  A1: 'Beginner',
  A2: 'Elementary',
  B1: 'Intermediate',
  B2: 'Upper Intermediate',
  C1: 'Advanced',
  C2: 'Mastery',
};

export interface Lesson {
  id: string;
  categoryId: string;
  level: Level;
  title: string;
  titleEs: string;
  description: string;
  descriptionEs: string;
  words: Word[];
}

export interface Category {
  id: string;
  name: string;
  nameEs: string;
  icon: string;
  color: string;
  description: string;
  descriptionEs: string;
  lessons: Lesson[];
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

const numbersBeyond100Words: Word[] = NUMBER_MILESTONES.map(
  ({ value, emoji }) => {
    const words = numberToWords(value);
    return {
      id: `nb${value}`,
      en: capitalize(words.en),
      es: capitalize(words.es),
      ar: words.ar,
      emoji,
      context: {
        es: `El billete cuesta ${words.es} euros.`,
        en: `The ticket costs ${words.en} euros.`,
        ar: `التذكرة تكلفتها ${words.ar} يورو.`,
      },
    };
  },
);

