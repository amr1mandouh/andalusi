export function getAllLessons(): Lesson[] {
  return categories.flatMap((c) => c.lessons);
}

export function getLessonsByLevel(level: Level): Lesson[] {
  return getAllLessons().filter((l) => l.level === level);
}

export function getLessonsGroupedByLevel(): Record<Level, Lesson[]> {
  const all = getAllLessons();
  return LEVELS.reduce(
    (acc, level) => {
      acc[level] = all.filter((l) => l.level === level);
      return acc;
    },
    {} as Record<Level, Lesson[]>,
  );
}

export function getLessonById(id: string): Lesson | undefined {
  return getAllLessons().find((l) => l.id === id);
}

// Used by the post-lesson summary screen's "Continue to next lesson" choice.
// Walks the learner's own level first (in its natural order), then falls
// back to the first lesson of the next level so progression never dead-ends
// mid-level. Returns undefined once every lesson has been walked.
export function getNextLesson(currentLessonId: string): Lesson | undefined {
  const current = getLessonById(currentLessonId);
  if (!current) return undefined;

  const sameLevel = getLessonsByLevel(current.level);
  const indexInLevel = sameLevel.findIndex((l) => l.id === currentLessonId);
  if (indexInLevel !== -1 && indexInLevel < sameLevel.length - 1) {
    return sameLevel[indexInLevel + 1];
  }

  const levelIndex = LEVELS.indexOf(current.level);
  for (let i = levelIndex + 1; i < LEVELS.length; i++) {
    const nextLevelLessons = getLessonsByLevel(LEVELS[i]);
    if (nextLevelLessons.length > 0) return nextLevelLessons[0];
  }

  return undefined;
}

export function getCategoryById(id: string): Category | undefined {
  return categories.find((c) => c.id === id);
}

export function getTotalWordCount(): number {
  return getAllLessons().reduce((sum, l) => sum + l.words.length, 0);
}

/**
 * Ranks categories by relevance to the learner's placed level, so the
 * Smart Dashboard surfaces content that actually matches them instead of
 * always leading with beginner categories like Greetings. Categories that
 * have lessons *at* the learner's level come first; the rest are ordered
 * by how close their nearest lesson is to that level. A null level (no
 * placement done yet) falls back to the original catalogue order.
 */
export function getRecommendedCategories(level: Level | null): Category[] {
  const withLessons = categories.filter((c) => c.lessons.length > 0);
  if (!level) return withLessons;

  const levelIndex = LEVELS.indexOf(level);
  const distanceFor = (cat: Category) => {
    let hasExact = false;
    let minDistance = Infinity;
    for (const lesson of cat.lessons) {
      const d = Math.abs(LEVELS.indexOf(lesson.level) - levelIndex);
      if (d === 0) hasExact = true;
      if (d < minDistance) minDistance = d;
    }
    return { hasExact, minDistance };
  };

  return [...withLessons].sort((a, b) => {
    const da = distanceFor(a);
    const db = distanceFor(b);
    if (da.hasExact !== db.hasExact) return da.hasExact ? -1 : 1;
    return da.minDistance - db.minDistance;
  });
}

export function getWordWithContext(
  wordId: string,
): { word: Word; lesson: Lesson; category: Category } | undefined {
  for (const category of categories) {
    for (const lesson of category.lessons) {
      const word = lesson.words.find((w) => w.id === wordId);
      if (word) return { word, lesson, category };
    }
  }
  return undefined;
}
